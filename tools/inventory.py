#!/usr/bin/env python3
"""Write docs/SKILLS.md: every skill and plugin installed for Codex and Claude Code.

    python3 ~/.agents/agent-setup/tools/inventory.py

Read-only on your settings: it only looks at folders and writes one file in this repo.
"""
import json
import os
import re
import time

HOME = os.path.expanduser("~")
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "docs", "SKILLS.md")

SKILL_DIRS = {
    "codex": [os.path.join(HOME, ".agents", "skills"), os.path.join(HOME, ".codex", "skills")],
    "claude": [os.path.join(HOME, ".claude", "skills")],
}


def describe(skill_md):
    try:
        text = open(skill_md, encoding="utf-8").read()
    except OSError:
        return ""
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    if not m:
        return ""
    lines = m.group(1).splitlines()
    for i, line in enumerate(lines):
        if line.startswith("description:"):
            value = line.split(":", 1)[1].strip().strip('"').strip("'")
            if value in (">", "|", ">-", "|-", ""):
                parts = []
                for nxt in lines[i + 1:]:
                    if nxt.startswith((" ", "\t")):
                        parts.append(nxt.strip())
                    else:
                        break
                value = " ".join(parts)
            value = value.replace("|", "/").replace(" \u2014 ", ", ").replace("\u2014", ", ")
            first = re.split(r"(?<=[.!?])\s", value, maxsplit=1)[0]
            return first[:140] + ("..." if len(first) > 140 else "")
    return ""


def scan_skills():
    found = {}
    for tool, dirs in SKILL_DIRS.items():
        for d in dirs:
            if not os.path.isdir(d):
                continue
            for name in sorted(os.listdir(d)):
                path = os.path.join(d, name, "SKILL.md")
                if name.startswith(".") or not os.path.isfile(path):
                    continue
                entry = found.setdefault(name, {"codex": False, "claude": False, "desc": ""})
                entry[tool] = True
                entry["desc"] = entry["desc"] or describe(path)
    return found


def codex_disabled_skills():
    path = os.path.join(HOME, ".codex", "config.toml")
    try:
        text = open(path, encoding="utf-8").read()
    except OSError:
        return set()
    disabled = set()
    for block in re.findall(r"\[\[skills\.config\]\](.*?)(?=\n\[|\Z)", text, re.S):
        p = re.search(r'path\s*=\s*"([^"]+)"', block)
        e = re.search(r"enabled\s*=\s*(true|false)", block)
        if p and e and e.group(1) == "false":
            disabled.add(os.path.basename(os.path.dirname(p.group(1))))
    return disabled


def codex_plugins():
    path = os.path.join(HOME, ".codex", "config.toml")
    try:
        text = open(path, encoding="utf-8").read()
    except OSError:
        return {}
    plugins = {}
    for name, body in re.findall(r'\[plugins\."([^"]+)"\](.*?)(?=\n\[|\Z)', text, re.S):
        e = re.search(r"enabled\s*=\s*(true|false)", body)
        plugins[name] = (e.group(1) == "true") if e else True
    return plugins


def claude_plugins():
    try:
        data = json.load(open(os.path.join(HOME, ".claude", "settings.json"), encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return {k: bool(v) for k, v in (data.get("enabledPlugins") or {}).items()}


def mark(on, off=False):
    return "off" if off else ("yes" if on else "")


def main():
    skills = scan_skills()
    disabled = codex_disabled_skills()
    lines = [
        "# Installed skills and plugins",
        "",
        f"_Generated by `tools/inventory.py` on {time.strftime('%Y-%m-%d')}. Re-run it after adding or removing skills._",
        "",
        "`yes` = installed and on, `off` = installed but turned off.",
        "",
        "## Skills",
        "",
        "| Skill | Codex | Claude Code | What it does |",
        "|---|:-:|:-:|---|",
    ]
    for name in sorted(skills, key=str.lower):
        s = skills[name]
        lines.append(f"| `{name}` | {mark(s['codex'], name in disabled and s['codex'])} | "
                     f"{mark(s['claude'])} | {s['desc']} |")
    cx, cc = codex_plugins(), claude_plugins()
    lines += ["", "## Plugins", "", "| Plugin | Codex | Claude Code |", "|---|:-:|:-:|"]
    for name in sorted(set(cx) | set(cc), key=str.lower):
        lines.append(f"| `{name}` | {mark(cx.get(name, False), name in cx and not cx[name])} | "
                     f"{mark(cc.get(name, False), name in cc and not cc[name])} |")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    both = sum(1 for s in skills.values() if s["codex"] and s["claude"])
    print(f"Wrote {OUT}: {len(skills)} skills ({both} in both tools), "
          f"{len(set(cx) | set(cc))} plugins.")


if __name__ == "__main__":
    main()
